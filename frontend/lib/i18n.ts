export function makeFmt(lang: Lang) {
  const loc = lang === "fa" ? "fa-IR" : "en-US";
  const n = new Intl.NumberFormat(loc, { maximumFractionDigits: 0 });
  const c = new Intl.NumberFormat(loc, { notation: "compact", maximumFractionDigits: 1 });
  const p = new Intl.NumberFormat(loc, { style: "percent", signDisplay: "exceptZero", maximumFractionDigits: 1 });
  const sh = new Intl.NumberFormat(loc, { style: "percent", maximumFractionDigits: 0 });
  const two = new Intl.NumberFormat(loc, { minimumIntegerDigits: 2 });
  const rt = new Intl.RelativeTimeFormat(loc, { numeric: "auto" });
  return {
    n: (v: number) => n.format(Math.round(v)),
    c: (v: number) => (Math.abs(v) >= 10000 ? c.format(v) : n.format(Math.round(v))),
    pct: (v: number) => p.format(v / 100),
    share: (fraction: number) => sh.format(fraction),
    dur: (sec: number) => `${n.format(Math.floor(sec / 60))}:${two.format(Math.round(sec % 60))}`,
    hour: (ms: number) => new Date(ms).toLocaleTimeString(loc, { hour: "2-digit", minute: "2-digit" }),
    ago: (epochSec: number) => {
      const h = (Date.now() / 1000 - epochSec) / 3600;
      if (h < 1) return rt.format(-Math.max(1, Math.round(h * 60)), "minute");
      return h < 24 ? rt.format(-Math.round(h), "hour") : rt.format(-Math.round(h / 24), "day");
    },
  };
}
export type Fmt = ReturnType<typeof makeFmt>;
export const label = (t: Dict, prefix: string, key: string) => (t as Record<string, string>)[`${prefix}_${key}`] ?? key;
